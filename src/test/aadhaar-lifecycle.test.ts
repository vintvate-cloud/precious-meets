import { describe, expect, it, beforeEach, vi } from "vitest";
import { ApplicationsService, MemberApplication } from "@/lib/applications-service";
import { EmailService } from "@/lib/email-service";

const MOCK_STORAGE_KEY = "precious_meets_member_applications_dossiers";

const mockApplication: MemberApplication = {
  id: "app-test-001",
  applicationReference: "PM-TEST-001",
  status: "pending_review",
  membershipStatus: "paid_pending_credentials",
  applicantName: "Aarav Sharma",
  applicantEmail: "aarav.test@preciousmeets.com",
  applicantPhone: "+91 98765 43210",
  applicantCity: "Delhi NCR",
  archetypeTitle: "The Philosophical Architect",
  archetypeDescription: "Deep contemplative visionary",
  archetypeTraits: ["Analytical", "Warm", "Curious"],
  socialEnergyScore: 65,
  conversationDepthScore: 85,
  playfulnessScore: 50,
  curiosityScore: 90,
  adventureScore: 60,
  dietaryPreference: "Flexible",
  allergies: [],
  personalBoundaries: [],
  sharedInterests: ["Literature", "Architecture"],
  quizAnswers: [],
  quizCompletedAt: "2026-10-25T09:30:00Z",
  paymentStatus: "paid",
  paymentAmountInr: 1999,
  paymentPlanTitle: "Precious Meets Membership",
  paidAt: "2026-10-25T10:00:00Z",
  identityStatus: "pending",
  identityProvider: "aadhaar_card_upload",
  aadhaarFileName: "aarav_aadhaar.jpg",
  credentialsSent: false,
  createdAt: "2026-10-25T09:30:00Z",
  updatedAt: "2026-10-25T10:00:00Z",
};

describe("Aadhaar Verification Lifecycle & Re-upload Service", () => {
  beforeEach(() => {
    localStorage.clear();
    localStorage.setItem(MOCK_STORAGE_KEY, JSON.stringify([mockApplication]));
    vi.spyOn(EmailService, "send").mockResolvedValue({
      success: true,
      id: "mock_test_email_id_12345",
    });
  });

  it("approves Aadhaar and updates identity status to verified", async () => {
    const result = await ApplicationsService.approveAadhaar(mockApplication.id);
    expect(result.success).toBe(true);
    expect(result.application.identityStatus).toBe("verified");
    expect(result.application.identityVerifiedAt).toBeDefined();

    // Verify persisted in localStorage
    const saved = ApplicationsService.getApplicationById(mockApplication.id);
    expect(saved?.identityStatus).toBe("verified");
  });

  it("requests Aadhaar re-upload with custom feedback note", async () => {
    const result = await ApplicationsService.requestAadhaarReupload(
      mockApplication.id,
      "Please re-upload: Aadhaar corners were clipped",
      "Document photo was blurry and corners were not visible."
    );

    expect(result.success).toBe(true);
    expect(result.application.identityStatus).toBe("reupload_requested");
    expect(result.application.aadhaarRejectionFeedback).toBe(
      "Document photo was blurry and corners were not visible."
    );

    const saved = ApplicationsService.getApplicationById(mockApplication.id);
    expect(saved?.identityStatus).toBe("reupload_requested");
    expect(saved?.aadhaarRejectionFeedback).toBe(
      "Document photo was blurry and corners were not visible."
    );
  });

  it("submits re-uploaded Aadhaar and flags document for review", async () => {
    const result = await ApplicationsService.submitAadhaarReupload(
      mockApplication.id,
      "data:image/png;base64,sample_revised_aadhaar_stream",
      "revised_aadhaar_card.png"
    );

    expect(result.success).toBe(true);
    expect(result.application.identityStatus).toBe("reuploaded");
    expect(result.application.aadhaarFileName).toBe("revised_aadhaar_card.png");
    expect(result.application.aadhaarFileUrl).toBe("data:image/png;base64,sample_revised_aadhaar_stream");
    expect(result.application.aadhaarReuploadedAt).toBeDefined();

    const saved = ApplicationsService.getApplicationById(mockApplication.id);
    expect(saved?.identityStatus).toBe("reuploaded");
  });

  it("rejects application with refund guarantee note", async () => {
    const result = await ApplicationsService.rejectWithRefund(
      mockApplication.id,
      "Identity verification could not be validated. Initiating 100% refund."
    );

    expect(result.success).toBe(true);
    expect(result.application.status).toBe("rejected");
    expect(result.application.paymentStatus).toBe("refunded");

    const saved = ApplicationsService.getApplicationById(mockApplication.id);
    expect(saved?.status).toBe("rejected");
    expect(saved?.paymentStatus).toBe("refunded");
  });

  it("dispatches initial credentials and enables credentialsSent flag", async () => {
    // Approve first
    await ApplicationsService.approveAadhaar(mockApplication.id);
    await ApplicationsService.approveApplication(mockApplication.id, "Approved for testing");

    const result = await ApplicationsService.sendMemberCredentials(mockApplication.id);
    expect(result.success).toBe(true);
    expect(result.application.credentialsSent).toBe(true);
    expect(result.application.autoGeneratedPassword).toBeDefined();
    expect(result.application.autoGeneratedPassword?.length).toBeGreaterThanOrEqual(16);
    expect(result.application.credentialsSentAt).toBeDefined();

    const initialPassword = result.application.autoGeneratedPassword;

    // Verify persisted
    const saved = ApplicationsService.getApplicationById(mockApplication.id);
    expect(saved?.credentialsSent).toBe(true);
    expect(saved?.autoGeneratedPassword).toBe(initialPassword);
  });

  it("reassigns new credentials, invalidating the old password and updating credentialsSentAt", async () => {
    // Approve and send initial credentials
    await ApplicationsService.approveAadhaar(mockApplication.id);
    await ApplicationsService.approveApplication(mockApplication.id, "Approved for testing");
    const initialResult = await ApplicationsService.sendMemberCredentials(mockApplication.id);
    const initialPassword = initialResult.application.autoGeneratedPassword;
    const initialSentAt = initialResult.application.credentialsSentAt;

    // Reassign credentials
    const reassignedResult = await ApplicationsService.reassignMemberCredentials(mockApplication.id);
    expect(reassignedResult.success).toBe(true);
    expect(reassignedResult.application.credentialsSent).toBe(true);
    expect(reassignedResult.application.autoGeneratedPassword).toBeDefined();
    expect(reassignedResult.application.autoGeneratedPassword?.length).toBeGreaterThanOrEqual(16);

    // Old password must be replaced and invalidated
    const newPassword = reassignedResult.application.autoGeneratedPassword;
    expect(newPassword).not.toBe(initialPassword);

    // Check localStorage reflects the reassigned password
    const saved = ApplicationsService.getApplicationById(mockApplication.id);
    expect(saved?.autoGeneratedPassword).toBe(newPassword);
    expect(saved?.autoGeneratedPassword).not.toBe(initialPassword);
  });
});

