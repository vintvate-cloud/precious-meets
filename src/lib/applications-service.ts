export type ApplicationStatus =
  | "draft"
  | "quiz_completed"
  | "paid_pending_credentials"
  | "pending_review"
  | "approved"
  | "rejected";

export type MembershipStatus =
  | "quiz_completed"
  | "paid_pending_credentials"
  | "active"
  | "rejected"
  | "suspended";

export type IdentityStatus =
  | "unverified"
  | "pending"
  | "verified"
  | "failed"
  | "manual_review"
  | "reupload_requested"
  | "reuploaded"
  | "rejected";
export type PaymentStatus = "pending" | "paid" | "refunded" | "failed";

export interface QuizAnswerRecord {
  questionNumber: number;
  questionTitle: string;
  category: string;
  answerLabel: string;
}

