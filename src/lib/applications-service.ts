  /**
   * Requests member to re-upload their Aadhaar document.
   * Dispatches custom safety email with admin's feedback and re-verification link.
   */
  static async requestAadhaarReupload(
    id: string,
    subject?: string,
    feedback?: string
  ): Promise<{ success: boolean; application: MemberApplication }> {
    const apps = this.loadApplications();
    const index = apps.findIndex((a) => a.id === id);

    if (index === -1) {
      throw new Error(`Dossier with ID ${id} not found.`);
    }

    const app = apps[index];
    const now = new Date().toISOString();
    const feedbackNote =
      feedback ||
      "Your uploaded Aadhaar document was unclear or unreadable. Please re-upload a clear copy so our team can complete your identity verification.";

    app.identityStatus = "reupload_requested";
    app.aadhaarRejectionFeedback = feedbackNote;
    app.updatedAt = now;

    const reverifyUrl = typeof window !== "undefined"
      ? `${window.location.origin}/verify-identity?appId=${encodeURIComponent(app.id)}&reupload=true&email=${encodeURIComponent(app.applicantEmail)}`
      : `https://preciousmeets.com/verify-identity?appId=${encodeURIComponent(app.id)}&reupload=true&email=${encodeURIComponent(app.applicantEmail)}`;

    try {
      await EmailService.send({
        to: app.applicantEmail,
        subject: subject || "Action Required: Please Re-verify Your Aadhaar Document | Precious Meets",
        template: "aadhaar_reverify_required",
        data: {
          name: app.applicantName,
          feedback: feedbackNote,
          reverifyUrl,
          applicationReference: app.applicationReference,
        },
      });
    } catch (err: any) {
      console.error("[ApplicationsService] Re-upload email dispatch error:", err);
      throw new Error("Failed to dispatch re-upload email to applicant: " + (err.message || String(err)));
    }

    apps[index] = app;
    this.saveApplications(apps);

    try {
      await supabase
        .from("member_applications")
        .update({
          identity_status: "reupload_requested",
          updated_at: now,
        })
        .eq("applicant_email", app.applicantEmail);
    } catch (e) {
      console.warn("[ApplicationsService] Supabase reupload_requested update notice:", e);
    }

    if (typeof window !== "undefined") {
      window.dispatchEvent(new Event("storage"));
      window.dispatchEvent(new CustomEvent("precious_meets_applications_updated"));
    }

    return { success: true, application: app };
  }

  /**
   * Member submits newly re-uploaded Aadhaar image or PDF.
   * Sets status to 'reuploaded', notifying admin in real-time.
   */
  static async submitAadhaarReupload(
    idOrEmail: string,
    fileUrl: string,
    fileName: string
  ): Promise<{ success: boolean; application: MemberApplication }> {
    const apps = this.loadApplications();
    const clean = idOrEmail.trim().toLowerCase();
    const index = apps.findIndex(
      (a) => a.id.toLowerCase() === clean || a.applicantEmail.toLowerCase() === clean
    );

    if (index === -1) {
      throw new Error("Application record not found.");
    }

    const app = apps[index];
    const now = new Date().toISOString();

    app.aadhaarFileUrl = fileUrl;
    app.aadhaarFileName = fileName;
    app.identityStatus = "reuploaded";
    app.aadhaarReuploadedAt = now;
    app.updatedAt = now;

    apps[index] = app;
    this.saveApplications(apps);

    try {
      await supabase
        .from("member_applications")
        .update({
          identity_status: "reuploaded",
          aadhaar_file_url: fileUrl,
          aadhaar_file_name: fileName,
          updated_at: now,
        })
        .eq("applicant_email", app.applicantEmail);
    } catch (e) {
      console.warn("[ApplicationsService] Supabase submitAadhaarReupload notice:", e);
    }

    if (typeof window !== "undefined") {
      window.dispatchEvent(new Event("storage"));
      window.dispatchEvent(new CustomEvent("precious_meets_applications_updated"));
    }

    return { success: true, application: app };
  }

