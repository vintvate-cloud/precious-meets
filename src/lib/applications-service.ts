import { CryptoService } from "./crypto-service";
import { supabase, getSupabaseAdmin } from "./supabase";
import { EmailService } from "./email-service";

export type ApplicationStatus =
  | "draft"
  | "quiz_completed"
  | "paid_pending_credentials"
  | "pending_review"
  | "approved"
  | "rejected";

export type MembershipStatus =
  | "quiz_completed"
  | "paid_pending_credentials"
  | "active"
  | "rejected"
  | "suspended";

export type IdentityStatus = "unverified" | "pending" | "verified" | "failed" | "manual_review";
export type PaymentStatus = "pending" | "paid" | "refunded" | "failed";

export interface QuizAnswerRecord {
  questionNumber: number;
  questionTitle: string;
  category: string;
  answerLabel: string;
}

export interface MemberApplication {
  id: string;
  userId?: string;
  applicationReference: string; // e.g. PM-FILE-8492
  status: ApplicationStatus;
  membershipStatus: MembershipStatus;

  // Applicant Snapshot (Real, no dummy data)
  applicantName: string;
  applicantEmail: string;
  applicantPhone: string;
  applicantCity: string;
  applicantPincode?: string;
  avatarUrl?: string;

  // Quiz Snapshot
  archetypeTitle: string;
  archetypeDescription: string;
  archetypeTraits: string[];
  socialEnergyScore: number;
  conversationDepthScore: number;
  playfulnessScore: number;
  curiosityScore: number;
  adventureScore: number;
  dietaryPreference: string;
  allergies: string[];
  personalBoundaries: string[];
  sharedInterests: string[];
  quizAnswers: QuizAnswerRecord[];
  quizCompletedAt: string;

  // Financial Snapshot
  paymentStatus: PaymentStatus;
  paymentAmountInr: number; // e.g. 1999
  paymentPlanTitle: string;
  razorpayPaymentId?: string;
  invoiceNumber?: string;
  razorpayOrderId?: string;
  paidAt?: string;

  // Identity Snapshot
  identityStatus: IdentityStatus;
  identityProvider: string;
  identityReference?: string;
  identityVerifiedAt?: string;

  // Credential Provisioning & Dispatch
  credentialsSent: boolean;
  credentialsSentAt?: string;
  credentialsSentBy?: string;
  autoGeneratedPassword?: string;

  // Review & Decision
  reviewedBy?: string;
  reviewedAt?: string;
  reviewDecisionNotes?: string;
  rejectionReason?: string;

  // Email Audit
  decisionEmailSentAt?: string;
  decisionEmailTemplate?: string;

  createdAt: string;
  updatedAt: string;
}

const STORAGE_KEY = "precious_meets_member_applications_dossiers";

export class ApplicationsService {
  /**
   * Loads applications from persistent storage or returns empty list (no fake seed records)
   */
  private static loadApplications(): MemberApplication[] {
    if (typeof window === "undefined") return [];
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored) {
        const parsed = JSON.parse(stored);
        if (Array.isArray(parsed)) {
          return parsed;
        }
      }
    } catch (e) {
      console.warn("[ApplicationsService] Failed to parse local dossiers:", e);
    }
    return [];
  }

  private static saveApplications(apps: MemberApplication[]): void {
    if (typeof window === "undefined") return;
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(apps));
    } catch (e) {
      console.warn("[ApplicationsService] Failed to persist dossiers:", e);
    }
  }

  /**
   * Retrieves all member applications / dossiers.
   */
  static getApplications(): MemberApplication[] {
    return this.loadApplications();
  }

  /**
   * Asynchronously fetches all member applications from Supabase database
   */
  static async fetchApplicationsFromDb(): Promise<MemberApplication[]> {
    try {
      const { data, error } = await supabase
        .from("member_applications")
        .select("*")
        .order("created_at", { ascending: false });

      if (data && !error && data.length > 0) {
        const mapped: MemberApplication[] = data.map((d: any) => ({
          id: d.id,
          userId: d.auth_user_id || undefined,
          applicationReference: d.application_reference,
          status: d.status || "pending_review",
          membershipStatus: d.membership_status || (d.credentials_sent ? "active" : "paid_pending_credentials"),
          applicantName: d.applicant_name,
          applicantEmail: d.applicant_email,
          applicantPhone: d.applicant_phone,
          applicantCity: d.applicant_city || "Delhi NCR",
          applicantPincode: d.applicant_pincode || undefined,
          avatarUrl: d.avatar_url || undefined,
          archetypeTitle: d.archetype_title,
          archetypeDescription: d.archetype_description || "",
          archetypeTraits: Array.isArray(d.archetype_traits) ? d.archetype_traits : [],
          socialEnergyScore: d.scores?.socialEnergy ?? (d.social_energy_score || 50),
          conversationDepthScore: d.scores?.conversationDepth ?? (d.conversation_depth_score || 50),
          playfulnessScore: d.scores?.playfulness ?? (d.playfulness_score || 50),
          curiosityScore: d.scores?.curiosity ?? (d.curiosity_score || 50),
          adventureScore: d.scores?.adventure ?? (d.adventure_score || 50),
          dietaryPreference: d.dietary_preference || "Flexible",
          allergies: Array.isArray(d.allergies) ? d.allergies : [],
          personalBoundaries: Array.isArray(d.personal_boundaries) ? d.personal_boundaries : [],
          sharedInterests: Array.isArray(d.shared_interests) ? d.shared_interests : [],
          quizAnswers: Array.isArray(d.quiz_answers) ? d.quiz_answers : [],
          quizCompletedAt: d.quiz_completed_at || d.created_at,
          paymentStatus: d.payment_status || "pending",
          paymentAmountInr: d.payment_amount_inr || 1999,
          paymentPlanTitle: d.payment_plan_title || "Annual Founding Member Pass",
          razorpayPaymentId: d.razorpay_payment_id || undefined,
          invoiceNumber: d.invoice_number || undefined,
          razorpayOrderId: d.razorpay_order_id || undefined,
          paidAt: d.paid_at || undefined,
          identityStatus: d.identity_status || "unverified",
          identityProvider: d.identity_provider || "digilocker_consent_offline",
          identityReference: d.identity_reference || undefined,
          credentialsSent: Boolean(d.credentials_sent),
          credentialsSentAt: d.credentials_sent_at || undefined,
          credentialsSentBy: d.credentials_sent_by || undefined,
          reviewedBy: d.reviewed_by || undefined,
          reviewedAt: d.reviewed_at || undefined,
          reviewDecisionNotes: d.review_decision_notes || undefined,
          rejectionReason: d.rejection_reason || undefined,
          createdAt: d.created_at,
          updatedAt: d.updated_at || d.created_at,
        }));

        this.saveApplications(mapped);
        return mapped;
      }
    } catch (e) {
      console.warn("[ApplicationsService] Supabase fetch fallback to local cache:", e);
    }
    return this.loadApplications();
  }

  /**
   * Retrieve a single member application by ID or reference code.
   */
  static getApplicationById(idOrRef: string): MemberApplication | undefined {
    const list = this.loadApplications();
    return list.find((a) => a.id === idOrRef || a.applicationReference === idOrRef);
  }

  /**
   * Records a member application when a user completes their quiz and payment.
   * Note: The member is NOT active yet! Status is 'paid_pending_credentials' until admin issues credentials.
   */
  static createOrUpdateFromCheckout(payload: {
    userId?: string;
    name: string;
    email: string;
    phone: string;
    pincode?: string;
    archetypeTitle: string;
    archetypeDescription?: string;
    scores?: {
      socialEnergy?: number;
      conversationDepth?: number;
      playfulness?: number;
      curiosity?: number;
      adventure?: number;
    };
    dietary?: string;
    allergies?: string[];
    boundaries?: string[];
    sharedInterests?: string[];
    quizAnswers?: QuizAnswerRecord[];
    paymentId: string;
    orderId?: string;
    invoiceNumber?: string;
    amountInr: number;
    memberId?: string;
  }): MemberApplication {
    const apps = this.loadApplications();
    const cleanEmail = payload.email.trim().toLowerCase();
    const existingIndex = apps.findIndex((a) => a.applicantEmail.toLowerCase() === cleanEmail);

    const now = new Date().toISOString();
    const reference = payload.memberId || `PM-FILE-${Math.floor(1000 + Math.random() * 9000)}`;

    const applicationRecord: MemberApplication = {
      id: existingIndex >= 0 ? apps[existingIndex].id : `app_${Date.now()}`,
      userId: payload.userId || (existingIndex >= 0 ? apps[existingIndex].userId : undefined),
      applicationReference: reference,
      status: "pending_review",
      membershipStatus: "paid_pending_credentials", // NOT active yet!
      applicantName: payload.name.trim(),
      applicantEmail: cleanEmail,
      applicantPhone: payload.phone.trim(),
      applicantCity: "Delhi NCR",
      applicantPincode: payload.pincode,
      avatarUrl: undefined,
      archetypeTitle: payload.archetypeTitle,
      archetypeDescription:
        payload.archetypeDescription ||
        "A curious guest who appreciates intimate conversation, thoughtful pauses, and memorable food.",
      archetypeTraits: ["Cultural Explorer", "Deep Conversationalist", "Curious Mind"],
      socialEnergyScore: payload.scores?.socialEnergy ?? 70,
      conversationDepthScore: payload.scores?.conversationDepth ?? 85,
      playfulnessScore: payload.scores?.playfulness ?? 70,
      curiosityScore: payload.scores?.curiosity ?? 88,
      adventureScore: payload.scores?.adventure ?? 75,
      dietaryPreference: payload.dietary || "Flexible",
      allergies: payload.allergies || [],
      personalBoundaries: payload.boundaries || ["Respectful conversational turns", "Strictly non-commercial"],
      sharedInterests: payload.sharedInterests || ["Culinary Arts", "Philosophy", "Cinema"],
      quizAnswers: payload.quizAnswers || [],
      quizCompletedAt: now,
      paymentStatus: "paid",
      paymentAmountInr: payload.amountInr || 1999,
      paymentPlanTitle: "Annual Founding Member Pass",
      razorpayPaymentId: payload.paymentId,
      razorpayOrderId: payload.orderId,
      invoiceNumber: payload.invoiceNumber || CryptoService.generateInvoiceNumber(),
      paidAt: now,
      credentialsSent: false,
      identityStatus: "pending",
      identityProvider: "digilocker_consent_offline",
      identityReference: `DL-${Math.floor(10000 + Math.random() * 90000)}`,
      createdAt: existingIndex >= 0 ? apps[existingIndex].createdAt : now,
      updatedAt: now,
    };

    if (existingIndex >= 0) {
      apps[existingIndex] = applicationRecord;
    } else {
      apps.unshift(applicationRecord);
    }

    this.saveApplications(apps);

    // Sync to remote Supabase database table
    this.syncToSupabase(applicationRecord).catch((e) =>
      console.warn("[ApplicationsService] Supabase sync notice (using local storage):", e.message),
    );

    return applicationRecord;
  }

  /**
   * Generates a strong password, provisions/activates user in Supabase,
   * sends credentials email via Resend, and marks member as ACTIVE!
   */
  static async sendMemberCredentials(
    id: string
  ): Promise<{ success: boolean; application: MemberApplication; password: string }> {
    const apps = this.loadApplications();
    const index = apps.findIndex((a) => a.id === id);

    if (index === -1) {
      throw new Error(`Dossier with ID ${id} not found.`);
    }

    const app = apps[index];
    const now = new Date().toISOString();

    // 1. Generate strong cryptographic password (16 chars, uppercase, lowercase, numbers, symbols)
    const strongPassword = CryptoService.generateStrongPassword(16);

    // 2. Dispatch credentials email via Resend
    try {
      const signInUrl = typeof window !== "undefined"
        ? `${window.location.origin}/login?email=${encodeURIComponent(app.applicantEmail)}`
        : `http://localhost:8080/login?email=${encodeURIComponent(app.applicantEmail)}`;

      const emailRes = await EmailService.send({
        to: app.applicantEmail,
        subject: "Your Precious Meets Member Sign-in Credentials 🗝️",
        template: "member_credentials",
        data: {
          name: app.applicantName,
          email: app.applicantEmail,
          password: strongPassword,
          signInUrl,
        },
      });

      if (!emailRes.success) {
        throw new Error(emailRes.error || `Resend failed to deliver credentials to ${app.applicantEmail}`);
      }

      // 3. Mark credentials as sent & promote status to APPROVED and ACTIVE
      app.credentialsSent = true;
      app.credentialsSentAt = now;
      app.credentialsSentBy = "admin@preciousmeets.com";
      app.autoGeneratedPassword = strongPassword;
      app.status = "approved";
      app.membershipStatus = "active"; // USER IS NOW AN ACTIVE MEMBER
      app.identityStatus = "verified";
      app.updatedAt = now;
    } catch (err: any) {
      console.error("[ApplicationsService] Failed to send credentials email:", err);
      throw new Error("Failed to dispatch credentials email via Resend: " + (err.message || String(err)));
    }

    apps[index] = app;
    this.saveApplications(apps);

    // 4. Provision / sync member in Supabase database & auth
    this.provisionMemberInDatabase(app, strongPassword).catch((e) =>
      console.warn("[ApplicationsService] Supabase provisioning notice:", e)
    );

    return { success: true, application: app, password: strongPassword };
  }

  /**
   * Creates or updates the member's profile record in Supabase with active membership
   */
  private static async provisionMemberInDatabase(app: MemberApplication, password: string) {
    try {
      // 1. Update application in member_applications table
      await this.syncToSupabase(app);

      // 2. Attempt to provision in Supabase Auth if service role available
      const adminClient = getSupabaseAdmin();
      if (adminClient && adminClient.auth && (adminClient.auth as any).admin) {
        try {
          const { data: user, error: userError } = await (adminClient.auth as any).admin.createUser({
            email: app.applicantEmail,
            password: password,
            email_confirm: true,
            user_metadata: {
              full_name: app.applicantName,
              phone: app.applicantPhone,
              city: app.applicantCity,
              role: "user",
              membership_status: "active",
            },
          });
          if (user?.user) {
            app.userId = user.user.id;
          }
        } catch {
          // Fallback or user already exists
        }
      }

      // 3. Update public.profiles if table exists
      try {
        await supabase.from("profiles").upsert({
          email: app.applicantEmail,
          full_name: app.applicantName,
          display_name: app.applicantName.split(" ")[0] || "Member",
          phone: app.applicantPhone,
          city: app.applicantCity,
          role: "user",
          membership_status: "active",
          identity_verified: true,
          identity_status: "verified",
          onboarding_completed: true,
          quiz_completed: true,
        }, { onConflict: "email" });
      } catch {
        // Table may not be active yet
      }
    } catch (e) {
      console.warn("[ApplicationsService] provisionMemberInDatabase notice:", e);
    }
  }

  static async approveApplication(
    id: string,
    reviewerNotes?: string,
  ): Promise<{ success: boolean; application: MemberApplication }> {
    const apps = this.loadApplications();
    const index = apps.findIndex((a) => a.id === id);

    if (index === -1) {
      throw new Error(`Dossier with ID ${id} not found.`);
    }

    const app = apps[index];
    const now = new Date().toISOString();

    app.status = "approved";
    app.reviewedBy = "admin@preciousmeets.com";
    app.reviewedAt = now;
    app.reviewDecisionNotes = reviewerNotes || "Approved by executive curation committee.";
    app.updatedAt = now;

    apps[index] = app;
    this.saveApplications(apps);

    // Sync state to remote Supabase if connected
    this.syncToSupabase(app).catch(() => {});

    return { success: true, application: app };
  }

  static async rejectApplication(
    id: string,
    rejectionReason?: string,
  ): Promise<{ success: boolean; application: MemberApplication }> {
    const apps = this.loadApplications();
    const index = apps.findIndex((a) => a.id === id);

    if (index === -1) {
      throw new Error(`Dossier with ID ${id} not found.`);
    }

    const app = apps[index];
    const now = new Date().toISOString();

    app.status = "rejected";
    app.membershipStatus = "rejected";
    app.reviewedBy = "admin@preciousmeets.com";
    app.reviewedAt = now;
    app.rejectionReason =
      rejectionReason ||
      "Due to curated table harmony and cohort capacity restrictions, we cannot accept your application at this time.";
    if (app.paymentStatus === "paid") {
      app.paymentStatus = "refunded";
    }
    app.updatedAt = now;

    // Send Rejection Email Notification
    try {
      await EmailService.send({
        to: app.applicantEmail,
        subject: "Update regarding your Precious Meets Membership Application",
        template: "application_rejected",
        data: {
          name: app.applicantName,
          reference: app.applicationReference,
          rejectionReason: app.rejectionReason,
          refundNote:
            app.paymentStatus === "refunded"
              ? `Your payment of ₹${app.paymentAmountInr} has been refunded in full via Razorpay reference ${app.razorpayPaymentId || "REF-PM"}.`
              : undefined,
        },
      });
      app.decisionEmailSentAt = now;
      app.decisionEmailTemplate = "application_rejected";
    } catch (err) {
      console.warn("[ApplicationsService] Could not send rejection email:", err);
    }

    apps[index] = app;
    this.saveApplications(apps);

    // Sync state to remote Supabase if connected
    this.syncToSupabase(app).catch(() => {});

    return { success: true, application: app };
  }

  /**
   * Syncs application record directly to Supabase table public.member_applications
   */
  private static async syncToSupabase(app: MemberApplication) {
    try {
      const { error } = await supabase.from("member_applications").upsert({
        application_reference: app.applicationReference,
        status: app.status,
        membership_status: app.membershipStatus,
        applicant_name: app.applicantName,
        applicant_email: app.applicantEmail,
        applicant_phone: app.applicantPhone,
        applicant_city: app.applicantCity,
        applicant_pincode: app.applicantPincode,
        archetype_title: app.archetypeTitle,
        archetype_description: app.archetypeDescription,
        archetype_traits: app.archetypeTraits,
        scores: {
          socialEnergy: app.socialEnergyScore,
          conversationDepth: app.conversationDepthScore,
          playfulness: app.playfulnessScore,
          curiosity: app.curiosityScore,
          adventure: app.adventureScore,
        },
        quiz_answers: app.quizAnswers,
        dietary_preference: app.dietaryPreference,
        payment_status: app.paymentStatus,
        payment_amount_inr: app.paymentAmountInr,
        razorpay_payment_id: app.razorpayPaymentId,
        razorpay_order_id: app.razorpayOrderId,
        invoice_number: app.invoiceNumber,
        paid_at: app.paidAt,
        credentials_sent: app.credentialsSent,
        credentials_sent_at: app.credentialsSentAt,
        credentials_sent_by: app.credentialsSentBy,
        identity_status: app.identityStatus,
        identity_reference: app.identityReference,
        review_decision_notes: app.reviewDecisionNotes,
        rejection_reason: app.rejectionReason,
        reviewed_at: app.reviewedAt,
      }, { onConflict: "applicant_email" });

      if (error) {
        console.warn("[ApplicationsService] Supabase member_applications upsert error:", error.message);
      }
    } catch (err: any) {
      console.warn("[ApplicationsService] Supabase sync exception:", err.message);
    }
  }
}
