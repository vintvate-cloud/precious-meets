  /**
   * Permanently deletes a member application dossier directly from Supabase database.
   */
  static async deleteApplication(idOrEmail: string): Promise<MemberApplication[]> {
    const apps = this.loadApplications();
    const clean = idOrEmail.trim().toLowerCase();
    const cleanId = clean.replace("ver_", "");

    const updated = apps.filter(
      (a) =>
        a.id.toLowerCase() !== clean &&
        a.id.toLowerCase() !== cleanId &&
        a.applicantEmail.toLowerCase() !== clean &&
        a.applicationReference.toLowerCase() !== clean
    );

    this.saveApplications(updated);

    // Delete directly from Supabase member_applications table
    try {
      await supabase
        .from("member_applications")
        .delete()
        .or(`id.eq.${cleanId},applicant_email.eq.${clean}`);
    } catch (e) {
      console.warn("[ApplicationsService] Supabase delete error:", e);
    }

    if (typeof window !== "undefined") {
      window.dispatchEvent(new Event("storage"));
      window.dispatchEvent(new CustomEvent("precious_meets_applications_updated"));
    }

    return updated;
  }

  /**
   * Syncs application record directly to Supabase table public.member_applications.
   */
  private static async syncToSupabase(app: MemberApplication): Promise<any> {
    try {
      const payload: any = {
        application_reference: app.applicationReference,
        status: app.status,
        membership_status: app.membershipStatus,
        applicant_name: app.applicantName,
        applicant_email: app.applicantEmail,
        applicant_phone: app.applicantPhone,
        applicant_city: app.applicantCity,
        applicant_pincode: app.applicantPincode,
        archetype_title: app.archetypeTitle,
        archetype_description: app.archetypeDescription,
        archetype_traits: app.archetypeTraits,
        scores: {
          socialEnergy: app.socialEnergyScore,
          conversationDepth: app.conversationDepthScore,
          playfulness: app.playfulnessScore,
          curiosity: app.curiosityScore,
          adventure: app.adventureScore,
          user_photo_url: app.userPhotoUrl || app.avatarUrl,
          user_photo_name: app.userPhotoFileName,
        },
        quiz_answers: app.quizAnswers,
        dietary_preference: app.dietaryPreference,
        payment_status: app.paymentStatus,
        payment_amount_inr: app.paymentAmountInr,
        razorpay_payment_id: app.razorpayPaymentId,
        razorpay_order_id: app.razorpayOrderId,
        invoice_number: app.invoiceNumber,
        paid_at: app.paidAt,
        credentials_sent: app.credentialsSent,
        credentials_sent_at: app.credentialsSentAt,
        credentials_sent_by: app.credentialsSentBy,
        identity_status: app.identityStatus,
        identity_reference: app.identityReference,
        aadhaar_file_url: app.aadhaarFileUrl,
        aadhaar_file_name: app.aadhaarFileName,
        user_photo_url: app.userPhotoUrl || app.avatarUrl,
        user_photo_name: app.userPhotoFileName,
        avatar_url: app.avatarUrl || app.userPhotoUrl,
        review_decision_notes: app.reviewDecisionNotes,
        rejection_reason: app.rejectionReason,
        reviewed_at: app.reviewedAt,
      };

      if (app.id && app.id.includes("-")) {
        payload.id = app.id;
      }

      let { data, error } = await supabase
        .from("member_applications")
        .upsert(payload, { onConflict: "applicant_email" })
        .select()
        .single();

      // Graceful fallback: If Supabase table schema hasn't executed migration for user_photo_url / user_photo_name,
      // retry without those columns (they are safely preserved inside avatar_url and scores.user_photo_url)
      if (error && (error.code === "PGRST204" || error.message?.includes("column"))) {
        console.warn("[ApplicationsService] Supabase schema cache notice (missing user_photo columns). Retrying with schema-safe payload...");
        const safePayload = { ...payload };
        delete safePayload.user_photo_url;
        delete safePayload.user_photo_name;

        const retryRes = await supabase
          .from("member_applications")
          .upsert(safePayload, { onConflict: "applicant_email" })
          .select()
          .single();

        data = retryRes.data;
        error = retryRes.error;
      }

      if (error) {
        console.warn("[ApplicationsService] Supabase member_applications upsert warning:", error.message);
      } else if (data) {
        console.log("[ApplicationsService] Member application successfully saved to Supabase! ID:", data.id);
      }
      return data;
    } catch (err: any) {
      console.warn("[ApplicationsService] Supabase sync exception:", err.message);
      return null;
    }
  }
